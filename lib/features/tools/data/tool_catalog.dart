    'orichalcum': 'pickaxe:arcane',
  };

  static ToolDefinition? byId(String toolId) {
    for (final definition in all) {
      if (definition.id == toolId) return definition;
    }
    return null;
  }

  static List<ToolDefinition> forDiscipline(GatheringDiscipline discipline) {
    return all
        .where((definition) => definition.discipline == discipline)
        .toList(growable: false);
  }

  static ToolDefinition starterFor(GatheringDiscipline discipline) {
    return byId(starterIds[discipline]!)!;
  }

  static String? migratedLegacyPickaxeId(String legacyId) {
    return legacyPickaxeAliases[legacyId];
  }
